export function addRouteDetails(guide: Guide): Guide {
  const detail = DETAILS[guide.slug]
  if (!detail) return guide
  // 이미 개별 편집된 홍도·흑산도 본문은 보존하고, 나머지의 공통 템플릿만 교체한다.
  const preserveEditorial = guide.slug === "mokpo-hongdo" || guide.slug === "mokpo-heuksando"
  const related = guide.relatedGuides ?? []
  const checklistHref = "/guide/boarding-checklist"
  const sources = [...(guide.sources ?? []), ...(detail.sources ?? [])]
  return {
    ...guide,
    updated: "2026-09-07",
    sections: [...(preserveEditorial ? guide.sections ?? [] : []), ...detail.sections],
    tips: preserveEditorial ? guide.tips : undefined,
    faqs: preserveEditorial ? [...guide.faqs, detail.faq] : [detail.faq],
    sources: sources.filter((source, index) => sources.findIndex((item) => item.href === source.href) === index),
    relatedGuides: related.some((link) => link.href === checklistHref)
      ? related : [...related, { label: "공통 승선 준비물·차량 접수 점검표", href: checklistHref }],
    sourceNote: `${guide.sourceNote ?? ""} 항로별 준비 설명 보강: 2026-09-07. 이동·휴식·일정 구성은 FerryCast의 계획 제안이며 교통 연결이나 승선을 보장하지 않습니다. 링크된 자료의 시간표·운임은 출발일 기준으로 다시 확인하세요.`,
  }
}
